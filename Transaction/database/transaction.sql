
CREATE SEQUENCE CC_TRANSACTION_SEQ
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

CREATE TABLE CC_TRANSACTION (
    TRANSACTION_ID NUMBER(19,0) PRIMARY KEY,
    CARD_NUMBER VARCHAR2(20) NOT NULL,
    CUSTOMER_ID NUMBER(19,0),
    TRANSACTION_TYPE VARCHAR2(20) NOT NULL,
    AMOUNT NUMBER(19,2) NOT NULL,
    MERCHANT_ID NUMBER(19,0),
    TRANSACTION_DATE_TIME TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    STATUS VARCHAR2(20) NOT NULL,

    CONSTRAINT CHK_TRANSACTION_TYPE
        CHECK (TRANSACTION_TYPE IN ('PURCHASE', 'PAYMENT')),

    CONSTRAINT CHK_TRANSACTION_STATUS
        CHECK (STATUS IN ('SUCCESS', 'FAILED')),

    CONSTRAINT CHK_TRANSACTION_AMOUNT
        CHECK (AMOUNT > 0)
);


CREATE INDEX IDX_TX_CARD
    ON CC_TRANSACTION (CARD_NUMBER);

CREATE INDEX IDX_TX_CUSTOMER
    ON CC_TRANSACTION (CUSTOMER_ID);

CREATE INDEX IDX_TX_MERCHANT
    ON CC_TRANSACTION (MERCHANT_ID);

CREATE INDEX IDX_TX_DATE
    ON CC_TRANSACTION (TRANSACTION_DATE_TIME);

CREATE INDEX IDX_TX_TYPE_STATUS
    ON CC_TRANSACTION (TRANSACTION_TYPE, STATUS);


