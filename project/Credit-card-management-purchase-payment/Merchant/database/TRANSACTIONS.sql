    CARD_NUMBER NUMBER  NOT NULL,
    MERCHANT_ID NUMBER NOT NULL,
    TRANSACTION_TYPE VARCHAR(30),
    AMOUNT NUMBER NOT NULL,
    STATUS VARCHAR(15),
